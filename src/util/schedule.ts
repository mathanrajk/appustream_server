import cron from "node-cron";
import Audio from "#/model/audio";
import AutoPlaylist from "#/model/autoGeneratedPlaylist";

export const generatedPlaylist = async () => {
  try {
    const result = await Audio.aggregate([
      {
        $match: {
          category: { $exists: true, $ne: null },
        },
      },
      {
        $addFields: {
          likesCount: { $size: { $ifNull: ["$likes", []] } },
        },
      },
      {
        $sort: { likesCount: -1 },
      },
      {
        $group: {
          _id: "$category",
          audios: { $push: "$_id" },
        },
      },
      {
        $project: {
          _id: 1,
          audios: { $slice: ["$audios", 20] },
        },
      },
    ]);

    for (const item of result) {
      if (!item._id) continue;
      await AutoPlaylist.updateOne(
        { title: item._id.toString() },
        { $set: { items: item.audios, visibility: "auto" } },
        { upsert: true }
      );
    }
  } catch (error) {
    console.error("Error generating auto playlist:", error);
  }
};

// Generate auto playlists on server start
generatedPlaylist();

// Scheduled to run daily at midnight
cron.schedule("0 0 * * *", async () => {
  await generatedPlaylist();
});
